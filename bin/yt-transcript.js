#!/usr/bin/env node
"use strict";

// CLI: fetch a YouTube transcript and print it or save it to a file.
// Shares parsing, fetching, caching and formatting with server.js.
//
//   yt-transcript <url-or-id> [--format txt|srt|vtt] [--lang en] [-o file]
//   yt-transcript <url-or-id> --list-langs
//
// Exit codes: 0 ok, 1 fetch failure, 2 usage error.
const fs = require("node:fs");
const {
  parseVideoId,
  getTranscript,
  listTracks,
  mapTranscriptError,
  mapListError,
  validLang,
  sanitizeLang,
  FORMATTERS,
} = require("../server.js");

function formatHelp() {
  return [
    "Usage: yt-transcript <youtube-url-or-id> [options]",
    "",
    "Options:",
    "  -f, --format <txt|srt|vtt>  output format (default: txt)",
    "  -l, --lang <code>           caption language (default: first available)",
    "  -o, --output <file>         write to file instead of stdout",
    "      --list-langs            list available caption languages and exit",
    "  -h, --help                  show this help",
    "",
    "Option values accept space or = form (--format=srt). Use -- to end",
    "option parsing; files starting with - need the = form (--output=-f.txt).",
    "",
    "Examples:",
    "  yt-transcript https://www.youtube.com/watch?v=dQw4w9WgXcQ",
    "  yt-transcript dQw4w9WgXcQ -f srt -l en -o out.srt",
    "  yt-transcript dQw4w9WgXcQ --list-langs",
  ].join("\n");
}

function usageError(message) {
  const err = new Error(message);
  err.code = "USAGE";
  throw err;
}

function takeValue(argv, i, flag) {
  const value = argv[i + 1];
  if (value === undefined || value === "" || value.startsWith("-")) usageError(`Missing value for ${flag}.`);
  return value;
}

function takeEquals(value, flag) {
  if (!value) usageError(`Missing value for ${flag}.`);
  return value;
}

function parseArgs(argv) {
  const args = {
    input: null,
    format: "txt",
    lang: undefined,
    output: null,
    listLangs: false,
    help: false,
  };
  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--") {
      positional.push(...argv.slice(i + 1));
      break;
    } else if (a === "--help" || a === "-h") args.help = true;
    else if (a === "--list-langs") args.listLangs = true;
    else if (a === "--format" || a === "-f") args.format = takeValue(argv, i++, a);
    else if (a.startsWith("--format=")) args.format = takeEquals(a.slice("--format=".length), "--format");
    else if (a === "--lang" || a === "-l") args.lang = takeValue(argv, i++, a);
    else if (a.startsWith("--lang=")) args.lang = takeEquals(a.slice("--lang=".length), "--lang");
    else if (a === "--output" || a === "-o") args.output = takeValue(argv, i++, a);
    else if (a.startsWith("--output=")) args.output = takeEquals(a.slice("--output=".length), "--output");
    else if (a.startsWith("-") && a.length > 1) usageError(`Unknown option: ${a}`);
    else positional.push(a);
  }
  if (positional.length > 1) usageError("Expected a single YouTube URL or video ID.");
  args.input = positional[0] || null;
  return args;
}

// Runs the CLI. `io` defaults to the real console/fs and can be swapped in
// tests. Returns a numeric exit code; never calls process.exit itself.
async function run(argv, io = {}) {
  const out = io.stdout || process.stdout;
  const errOut = io.stderr || process.stderr;
  const writeFile = io.writeFile || fs.writeFileSync;
  let args;
  try {
    args = parseArgs(argv);
  } catch (e) {
    errOut.write(`Error: ${e.message}\n\n${formatHelp()}\n`);
    return 2;
  }
  if (args.help) {
    try {
      out.write(`${formatHelp()}\n`);
    } catch (e) {
      errOut.write(`Error: failed to write output: ${e.message}\n`);
      return 1;
    }
    return 0;
  }
  if (!args.input) {
    errOut.write(`Error: missing YouTube URL or video ID.\n\n${formatHelp()}\n`);
    return 2;
  }
  const videoId = parseVideoId(args.input);
  if (!videoId) {
    errOut.write(`Error: could not find a YouTube video ID in "${args.input}".\n`);
    return 2;
  }
  const format = String(args.format || "txt").toLowerCase();
  if (!Object.hasOwn(FORMATTERS, format)) {
    errOut.write("Error: format must be txt, srt or vtt.\n");
    return 2;
  }
  const lang = validLang(args.lang);
  if (lang === null) {
    errOut.write("Error: invalid lang code.\n");
    return 2;
  }
  if (args.listLangs) {
    try {
      const tracks = await listTracks(videoId);
      try {
        if (tracks.length === 0) out.write(`No caption tracks found for ${videoId}.\n`);
        for (const t of tracks) {
          out.write(`${t.languageCode} — ${t.name}${t.isAutoGenerated ? " (auto)" : ""}\n`);
        }
      } catch (e) {
        errOut.write(`Error: failed to write output: ${e.message}\n`);
        return 1;
      }
      return 0;
    } catch (e) {
      const { error } = mapListError(e, videoId);
      errOut.write(`Error: ${error}\n`);
      return 1;
    }
  }
  let cues, resolved, fetchedAt;
  try {
    ({ cues, lang: resolved, fetchedAt } = await getTranscript(videoId, lang));
  } catch (e) {
    const { error } = mapTranscriptError(e, videoId, args.input, lang);
    errOut.write(`Error: ${error}\n`);
    return 1;
  }
  const body = FORMATTERS[format](cues, {
    videoId,
    lang: sanitizeLang(resolved, lang),
    fetchedAt,
  });
  if (args.output) {
    try {
      writeFile(args.output, body, "utf8");
    } catch (e) {
      errOut.write(`Error: cannot write to "${args.output}": ${e.message}\n`);
      return 1;
    }
  } else {
    try {
      out.write(body);
    } catch (e) {
      errOut.write(`Error: failed to write output: ${e.message}\n`);
      return 1;
    }
  }
  return 0;
}

if (require.main === module) {
  run(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (e) => {
      process.stderr.write(`Error: ${e?.message || e}\n`);
      process.exit(1);
    }
  );
}

module.exports = { parseArgs, formatHelp, run };
